/**
 * Writes google-apps-script/InventorySeed.gs from data/products.generated.json.
 *
 * setupInventory() in Code.gs uses it to create a Products row for every
 * catalog product that doesn't have one yet. It is the INITIAL seed only:
 * existing rows (live stock) are never overwritten. Unknown stock stays null
 * (→ track_stock FALSE, blank stock), never 0.
 *
 * Runs as part of `npm run catalog:prepare`; or directly: npm run inventory:seed
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PRODUCTS = path.join(ROOT, "data", "products.generated.json");
const OUT = path.join(ROOT, "google-apps-script", "InventorySeed.gs");

const products = JSON.parse(readFileSync(PRODUCTS, "utf8")).filter((product) => product.status === "active");

for (const product of products) {
  if (product.stock !== null && !(Number.isInteger(product.stock) && product.stock >= 0)) {
    throw new Error(`${product.id}: stock must be a whole number ≥ 0 or null, got ${product.stock}`);
  }
}

const rows = products.map(
  (product) =>
    `  { productId: ${JSON.stringify(product.id)}, productName: ${JSON.stringify(product.name)}, stock: ${product.stock === null ? "null" : product.stock} }`,
);

const source = `/**
 * GENERATED by \`npm run catalog:prepare\` (scripts/generate-inventory-seed.mjs) — do not edit by hand.
 *
 * Initial inventory for setupInventory() in Code.gs. Used ONLY to create a
 * Products row for a product that doesn't have one yet; existing rows (live
 * stock) are never changed. stock: null = not tracked (NOT zero).
 *
 * Paste this file into the same Apps Script project as Code.gs.
 */

var SADIRA_PRODUCT_SEED = [
${rows.join(",\n")}
];
`;

writeFileSync(OUT, source);
// Content migration is separate from inventory and never overwrites live edits.
const catalogSeed = products.map(product => ({ ...product, detailsSource: null }));
writeFileSync(path.join(ROOT, "google-apps-script", "CatalogSeed.gs"),
  "/** GENERATED. Run setupCatalog() to add missing catalog rows without overwriting edits. */\nvar SADIRA_CATALOG_SEED = " + JSON.stringify(catalogSeed, null, 2) + ";\n");
const tracked = products.filter((product) => product.stock !== null).length;
console.log(`InventorySeed.gs: ${products.length} products (${tracked} with known stock).`);
